document.addEventListener("DOMContentLoaded", () => {
    const searchInput = document.getElementById("gameSearchInput");
    const resultsContainer = document.getElementById("searchResultsContainer");
    const resultsGrid = document.getElementById("searchResultsGrid");

    if (!searchInput || !resultsContainer || !resultsGrid) return;

    const getGameTitleFromHTML = (htmlString) => {
        const tempDiv = document.createElement("div");
        tempDiv.innerHTML = htmlString;
        const titleEl = tempDiv.querySelector(".grid-card-title");
        return titleEl ? titleEl.textContent.trim() : "";
    };

    searchInput.addEventListener("input", (e) => {
        const query = e.target.value.trim().toLowerCase();

        if (query === "") {
            resultsContainer.style.display = "none";
            resultsGrid.innerHTML = "";
            return;
        }

        const filteredGames = games.filter(htmlString => {
            const title = getGameTitleFromHTML(htmlString);
            return title.toLowerCase().startsWith(query);
        });

        resultsGrid.innerHTML = "";
        resultsContainer.style.display = "block";

        if (filteredGames.length === 0) {
            resultsGrid.innerHTML = `<div class="no-results">No games found starting with "${e.target.value}"</div>`;
            return;
        }

        filteredGames.forEach(htmlString => {
            resultsGrid.insertAdjacentHTML("beforeend", htmlString);
        });

        resultsGrid.querySelectorAll("img.lazy").forEach(img => {
            if (img.dataset.src) {
                img.src = img.dataset.src;
                img.classList.remove("lazy");
            }
        });

        resultsGrid.querySelectorAll(".grid-card").forEach(card => {
            card.addEventListener("click", () => {
                if (typeof selectGameCard === "function") {
                    selectGameCard(card);
                }
            });
        });
    });
});
